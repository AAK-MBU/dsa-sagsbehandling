   (deterministic) and kept as plain SQL. Expected after step 7:

     @skoleaar       Potentiel skolestarter   5 \ Ikke screenet tab (16)
                     Tid booket              11 /
                     Screening afviklet      47 \  (also its own tab)
                     Skoleplaceret           24  > Overblik tab (85)
                     Afsluttet               14 /
