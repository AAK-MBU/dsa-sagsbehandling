/* ============================================================
   Test-data reset + seed for a DSA dev database.

   DESTRUCTIVE: clears every case table (Skolebegynder, its changes,
   Sagsaktivitet, SkoleHistorik, Foraelder, Elev, Adresse, PortalAuditLog)
   and inserts a fictional cohort of skolebegyndere. Lookups are NOT
   touched — run seed_lookup_data.sql first.

   All names, CPR numbers and address ids are made up. The addresses are
   real Aarhus streets with invented numbers and GUIDs; nothing here links a
   person to a place.

   What the cohort covers — 106 children, 109 cases, generated by a script
   (deterministic) and kept as plain SQL. Expected after step 7:

     @skoleaar       Ikke screenet       16   (Ikke screenet tab)
                     Nærmere afklaring   13   (Nærmere afklaring tab)
                     Under behandling    34 \
                     Skoletilbud         24  > Overblik tab (72)
                     Afsluttet           14 /
     @skoleaar - 1   Afsluttet            8
     Ændringer       21 rows, 18 unhandled (Ændringer tab), all seven årsager

     - the 15 original children (Amira, Tomas, ...) unchanged
     - children whose school start was postponed ("Skolegangsudsat") last
       year and who are skolebegyndere again this year — the reason Skolebegynder
       has its own id rather than CPR as key
     - interrupted screenings, PPR cases and children recently moved to DK
     - siblings and twins sharing custody holders and address
     - two name- and address-protected children, one with a father who must
       not know the address
     - offers at a secondary campus, a specialklasse, and cases where district
       school, wanted school and offer differ (skoler_afviger)

   Dates are not hardcoded: every date, school year and child's birth year
   is derived from the run date (see "Datoankre" in step 2), as in
   befordringssystemet's seed. Run in October 2026, @skoleaar is 2027.

   The SX result values (samlet_resultat, puf_screeningsresultat) are
   ILLUSTRATIVE — the real categories have to be confirmed against SX.

   Statuses are not hand-set except Afsluttet: the cases are inserted as
   "Ikke screenet" and usp_recalculate_skolebegynder_status derives the rest,
   so this file also exercises the status rule.

   Requires migration 001, seed_lookup_data.sql (including Skolematrikel),
   the views and the stored procedure usp_recalculate_skolebegynder_status.

   Runs inside a transaction that ROLLBACKs by default — change the final
   ROLLBACK to COMMIT once the previewed data looks correct.
   ============================================================ */

