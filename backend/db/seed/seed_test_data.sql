DECLARE @nu    datetime2 = CAST(CAST(GETDATE() AS date) AS datetime2);

DECLARE @skoleaar int =
    CASE WHEN MONTH(@i_dag) >= 8 THEN YEAR(@i_dag) + 1 ELSE YEAR(@i_dag) END;

DECLARE @cpr_aar_skift int = @skoleaar - 2026;


