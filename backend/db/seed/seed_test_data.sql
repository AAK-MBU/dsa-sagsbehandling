/* ============================================================
   Datoankre
   ------------------------------------------------------------
   As in befordringssystemet's seed: every date below is derived from
   GETDATE() rather than written as a literal, so the data does not decay —
   a file with fixed dates shows last year's cohort, with screenings and
   letters that look a year old, once the calendar has moved on.

   The data is a snapshot of a cohort mid-season, measured back from the
   day the seed is run: the list was drawn ~6 months ago, screenings
   happened 7-14 weeks ago, school offers were given in the following
   weeks and the first cases closed in the last two weeks. The offsets are
   relative to the run date, not to the real screening calendar (Jan-Feb).

   @skoleaar is the cohort being worked on: the children starting school
   next August — this year before August, next year from August on.
   Children are born @skoleaar - 6 (postponed children a year earlier);
   @cpr_aar_skift moves the birth year in the fictional CPR numbers, which
   are written below for the 2026 cohort.
============================================================ */

